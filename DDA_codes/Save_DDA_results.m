function [Result] = Save_DDA_results(Input,Result)
% 1. Make file names, folders, etc. 
% 2. Save results
 
%% Make folder load/save structures:
% Input.linear_data_repo_folder='linear_data\';
% Input.save_repo_folder='DDA_data\';
 
% % Data subfolder
% % Input.rootfolder='Matlabbing\Matlab_large_files\';
% Input.rootfolder
% cd(Input.rootfolder)
% Data_w_folder = ['DDA/' Input.inversion_tool '/' ]; % whole folder handle
% % Data_w_folder = [ Input.rootfolder 'data/' Input.inversion_tool '/' ]; % whole folder handle
        
% form string from array size parameters:
array_str = char(join(string(Input.arrayN),'_'));

switch Input.sample.type
    case 'stl_file'         % 'lorentzian Au', 'ring', 'oligomer'
        file.name=[ Input.dimensionality '_'...
              'ds_' num2str(round(Input.dipole_spacing)*1e9) '_nm_' ...
              'stl_' strtok(Input.filename, '.') ...
              '.mat'];
        
    otherwise
        if isfield(Input, 'NLO_modality')
            file.name=[ Input.dimensionality '_'...
                Input.array_type '_'...
                'n_' strrep(num2str(Input.sample.n),'.','_')...
                'Px_' num2str(round(Input.p(1)*1e9,2))...
                'Py_' num2str(round(Input.p(2)*1e9,2))...
                '_theta' strrep(num2str(Input.theta),'.','_') ...
                '_phi' strrep(num2str(Input.phi),'.','_') ...
                '_psi' strrep(num2str(Input.psi),'.','_') ...
                '_N'  array_str  ...
                '_tau'  strrep(num2str(round(Input.particle.tau(2)*1e15,2)),'.','_')     ...
                '_lspr' strrep(num2str(round(Input.particle.lambda_peak_vec(2)*1e9,1)),'.','_') ...
                '_cs' strrep(num2str(round(Input.particle.scatter_strength*1e8,2)),'.','_') '.mat'];
          
            %% clean up cs string's white spaces:
            file.name=strrep(file.name,'  ','_');
            
%             file.name=[ Input.dimensionality '_'...
%                 Input.array_type '_'...
%                 'n_' strrep(num2str(Input.sample.n),'.','_')...
%                 'Px_' num2str(round(Input.p(1)*1e9))...
%                 'Py_' num2str(round(Input.p(2)*1e9))...
%                 '_theta' strrep(num2str(Input.theta),'.','_') ...
%                 '_phi' strrep(num2str(Input.phi),'.','_') ...
%                 '_psi' strrep(num2str(Input.psi),'.','_') ...
%                 '_N'  num2str(Input.arrayN)  ...
%                 '_tau'  strrep(num2str(round(Input.particle.tau(2)*1e15,2)),'.','_')     ...
%                 '_lspr' strrep(num2str(round(Input.particle.lambda_peak_vec(2)*1e9,1)),'.','_') ...
%                 '_cs' strrep(num2str(round(Input.particle.scatter_strength*1e8,2)),'.','_') ...
%                 '_'   num2str(Input.NLO_2D_limits(1)*1e9) ...
%                 '_to_' num2str(Input.NLO_2D_limits(2)*1e9) 'nm.mat'];
            
        else
            file.name=[ Input.dimensionality '_'...
                Input.array_type '_'...
                'n_' strrep(num2str(Input.sample.n),'.','_')...
                'Px_' num2str(round(Input.p(1)*1e9))...
                'Py_' num2str(round(Input.p(2)*1e9))...
                '_theta' strrep(num2str(Input.theta),'.','_') ...
                '_phi' strrep(num2str(Input.phi),'.','_') ...
                '_psi' strrep(num2str(Input.psi),'.','_') ...
                '_N'  array_str   ...
                '_tau'  strrep(num2str(round(Input.particle.tau(2)*1e15,2)),'.','_')     ...
                '_lsprx' strrep(num2str(round(Input.particle.lambda_peak_vec(1)*1e9,1)),'.','_') ...
                '_lspry' strrep(num2str(round(Input.particle.lambda_peak_vec(2)*1e9,1)),'.','_') ...
                '_cs' strrep(num2str(round(Input.particle.scatter_strength(1)*1e8,2)),'.','_') '.mat'];
             
            if isfield(Input.sample,'sticthing')
                file.name = replace(file.name,['_cs' strrep(num2str(round(Input.particle.scatter_strength*1e8,2)),'.','_') '.mat'],...
                                              ['_stitchX' strrep(num2str(round(Input.sample.sticthing(1)*1e9,2)),'.','_') ...
                                               '_Y' strrep(num2str(round(Input.sample.sticthing(2)*1e9,2)),'.','_')  '.mat']);
            end
        end
end
                            
%% remove unnecessary variables (which are only in the first Result(1)):
% from Array struct,  remove 'r_ij' and 'alpha' 'r_i_conv' fields:
fields={'r_ij','alpha','r_i_conv','r_i','alpha1','k'};
% fields={'r_ij','alpha','r_i_conv'};
I=find(isfield(Result(1),'Array.fields'));
if nnz(I)
    for ii=I
        Result(1).Array=rmfield(Result(1).Array,fields(ii));
    end
end

%% remove unnecessary vector exctinction variables:
% from Result.C struct:
fields={'sca_vec','abs_vec','ext_vec','sca_vec_max','abs_vec_max','ext_vec_max'};
I=find(isfield(Result(1).C,fields));
if nnz(I)
    for ii=I
        Result(1).C=rmfield(Result(1).C,fields(ii));
    end
end

% from Field and P struct:
switch Input.outputs
    case 'C_P_and_E'
        % from Field struct:
        if isfield(Result(1).Field,'Einc_N') ==1
            fields={'Einc_N'};
            Result(ii).Field=rmfield(Result(ii).Field,fields);
        elseif isfield(Result(1).Field,'Einc_3N') ==1
%             fields={'Einc_3N'};
%             Result(ii).Field=rmfield(Result(ii).Field,fields);
        end
end

%% save the data
% Data subfolder
[path] = Make_DDA_save_folder_and_name(Input,'DDA_results');
save([path file.name],'Input','Result','-v7.3'); % this gives
% surprisingly big files...
% save('save_tmp.mat','Input','Result', '-v7.3');

save([path file.name],'Input','Result', '-v7.3');
% save_big([path file.name],'Input','Result');
Result(1).filename=[path file.name];

cd(Input.code_rootfolder)

end